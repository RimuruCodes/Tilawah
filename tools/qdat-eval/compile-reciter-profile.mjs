// Aggregates the raw per-ayah cache build-reciter-profile.mjs writes into
// the small, checked-in src/lib/reciterStyleProfiles.js the app will read
// from at runtime (Phase 2, not built yet). Kept as a separate step —
// mirrors this project's existing extract/tune split (extract-features.mjs
// -> tune-thresholds.mjs) — so re-aggregating (e.g. after adding a reciter,
// or with a different sample) never re-runs the slow ASR extraction.
//
// Usage:
//   npx vite-node tools/qdat-eval/compile-reciter-profile.mjs -- --reciter Alafasy_128kbps
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

function parseArgs() {
  const args = process.argv.slice(2).filter((a) => a !== "--");
  const get = (flag) => {
    const i = args.indexOf(flag);
    return i === -1 ? null : args[i + 1];
  };
  return {
    reciterFolder: get("--reciter"),
    cacheDir: get("--cache-dir") || path.join("tools", "qdat-eval", "reciter-profile-cache"),
    outFile: get("--out") || path.join("src", "lib", "reciterStyleProfiles.js"),
  };
}

const mean = (arr) => (arr.length ? arr.reduce((a, b) => a + b, 0) / arr.length : null);
const round3 = (v) => (v == null ? null : Math.round(v * 1000) / 1000);

function loadExistingProfiles(outFile) {
  if (!fs.existsSync(outFile)) return {};
  const src = fs.readFileSync(outFile, "utf8");
  const match = src.match(/export const RECITER_STYLE_PROFILES = (\{[\s\S]*?\n\});/);
  if (!match) return {};
  // The file we write is trusted, machine-generated JSON-compatible JS (see
  // writeProfiles below) — safe to JSON.parse directly, no eval needed.
  return JSON.parse(match[1]);
}

function buildProfile({ reciterFolder, model, records }) {
  const ok = records.filter((r) => !r.error);
  const maddRatios = ok.flatMap((r) => r.maddRatios || []);
  const nasalRatios = ok.flatMap((r) => r.nasalRatios || []);
  const pauseDurationsSec = ok.flatMap((r) => r.pauseDurationsSec || []);
  const totalPauses = ok.reduce((s, r) => s + (r.pauseCount || 0), 0);
  const totalActiveSec = ok.reduce((s, r) => s + (r.activeDurationSec || 0), 0);
  const pitchVolatilities = ok.map((r) => r.pitchVolatility).filter((v) => v != null);

  return {
    reciterFolder,
    generatedAt: new Date().toISOString().slice(0, 10),
    model,
    sampleAyahs: ok.length,
    sampleErrors: records.length - ok.length,
    maddElongationMultiplier: round3(mean(maddRatios)),
    maddOccurrences: maddRatios.length,
    nasalHoldMultiplier: round3(mean(nasalRatios)),
    nasalOccurrences: nasalRatios.length,
    pauseRatePerActiveMinute: totalActiveSec > 0 ? round3(totalPauses / (totalActiveSec / 60)) : null,
    avgPauseDurationSec: round3(mean(pauseDurationsSec)),
    pauseOccurrences: pauseDurationsSec.length,
    pitchContourVolatilitySemitones: round3(mean(pitchVolatilities)),
    pitchSampleAyahs: pitchVolatilities.length,
  };
}

function writeProfiles(outFile, profiles) {
  const header = `// Per-reciter style profiles — statistical summaries (NOT a trained model) of
// how a specific reciter typically paces Madd elongation, nasal holds, and
// pauses, and how volatile their pitch contour is. Built for reciters with
// no QUA ground-truth timing (see quaReferenceData.js) so Tajweed checks can
// eventually compare a user against THAT reciter's own typical delivery
// instead of one generic baseline for every reciter (Phase 2 — not wired in
// yet; this file is data only).
//
// Generated by tools/qdat-eval/build-reciter-profile.mjs +
// compile-reciter-profile.mjs — do not hand-edit; re-run the scripts to
// update or add a reciter.
//
// Scope, deliberately narrow: every stat here is TIMING/RHYTHM/PITCH-
// CONTOUR-SHAPE only. maddElongationMultiplier and nasalHoldMultiplier are
// dimensionless duration ratios; pauseRatePerActiveMinute/avgPauseDurationSec
// are pure timing between words; pitchContourVolatilitySemitones is a
// standard deviation (shift-invariant, so it can't reflect pitch REGISTER)
// computed with no spectral/formant analysis (so it can't reflect voice
// TIMBRE either). Qalqalah bounce-dB is deliberately NOT profiled here — see
// build-reciter-profile.mjs's header comment for why.
export const RECITER_STYLE_PROFILES = `;
  const body = JSON.stringify(profiles, null, 2);
  fs.writeFileSync(outFile, `${header}${body};\n`);
}

function main() {
  const { reciterFolder, cacheDir, outFile } = parseArgs();
  if (!reciterFolder) {
    console.error("Usage: npx vite-node tools/qdat-eval/compile-reciter-profile.mjs -- --reciter <folder>");
    process.exit(1);
  }
  const cachePath = path.join(cacheDir, `${reciterFolder}.json`);
  if (!fs.existsSync(cachePath)) {
    console.error(`No cache found at ${cachePath} — run build-reciter-profile.mjs first.`);
    process.exit(1);
  }
  const cache = JSON.parse(fs.readFileSync(cachePath, "utf8"));
  const profile = buildProfile(cache);

  const profiles = loadExistingProfiles(outFile);
  profiles[reciterFolder] = profile;
  writeProfiles(outFile, profiles);

  console.log(`Wrote ${outFile} for ${reciterFolder}:`);
  console.log(JSON.stringify(profile, null, 2));
}

main();
